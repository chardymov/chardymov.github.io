  // ───────────────────────── портрет одного человека
  function portraitHtml(P0, opts) {
    opts = opts || {};
    var n = P0.name, out = '';
    var sexOn = hasBlock(P0, 'sex');
    var rows = AXIS_ORDER.filter(function (k) { return (!AXES[k].sex || sexOn) && axisScore(P0, k) != null; });
    var axHtml = rows.map(function (k) { return axisRow(AXES[k].title, AXES[k].lo, AXES[k].hi, axisScore(P0, k), undefined, n); }).join('');
    var texts = rows.map(function (k) {
      var lvl = axisLevel(axisScore(P0, k));
      return p(fill(AXES[k][lvl + 'T'], n));
    }).join('');

    var facts = [];
    var k = function (id) { return keys(P0, id); };
    if (k(5).length) facts.push(fill('{X} в ссоре ' + esc(words(FIGHT, k(5), ', а иногда ')) + '.', n));
    if (k(21).length) facts.push(fill('{X} считает главным в отношениях ' + esc(words(VALUE_ACC, k(21))) + '.', n));
    if (k(22).length) facts.push(fill('Через пять лет {X} видит пару так: ' + esc(words(FUTURE, k(22), '; ')) + '.', n));

    out += card(axHtml + texts + (facts.length ? p(facts.join(' '), 'margin:0') : ''));
    out += manualHtml(P0);
    return out;
  }

