  function summaryText(score) {
    if (score >= 75) return 'У вас высокая согласованность: во многих вещах вы смотрите на жизнь похоже. Ваша задача — не расслабляться и бережно обходиться с теми немногими темами, где вы различаетесь.';
    if (score >= 55) return 'У вас хорошая основа и несколько зон, где придётся договариваться. Это обычная и здоровая картина: различия — не несовместимость, а карта тем для разговора.';
    if (score >= 40) return 'Вы во многом разные. Это не приговор: пары с разными взглядами бывают очень крепкими, если различия названы вслух и по ним есть договорённости.';
    return 'Вы очень разные почти во всех блоках. Это повод для серьёзного, бережного разговора — возможно, с помощью семейного психолога, который поможет найти общий язык.';
  }

  function report(A, B, opts) {
    opts = opts || {};
    var cmp = compare(A, B), dyn = dynamics(A, B), html = '';
    var sexBoth = hasBlock(A, 'sex') && hasBlock(B, 'sex');

    // Шапка
    html += '<div style="text-align:center;padding:8px 0 4px">' +
      '<div style="font:500 13px/1.4 ' + FONT + ';letter-spacing:.08em;text-transform:uppercase;color:' + C.muted + '">Разбор пары</div>' +
      '<div style="font:600 26px/1.25 ' + FONT + ';color:' + C.ink + ';margin:6px 0 14px"><span style="color:' + C.a + '">' + esc(A.name) + '</span> &amp; <span style="color:' + C.b + '">' + esc(B.name) + '</span></div>' +
      '<div style="display:inline-block;background:' + C.accentSoft + ';border-radius:999px;padding:10px 22px;font:600 30px/1 ' + FONT + ';color:' + C.accent + '">' + cmp.score + '%</div>' +
      '<div style="font:400 13px/1.4 ' + FONT + ';color:' + C.muted + ';margin:8px 0 0">индекс согласованности</div></div>';
    html += p(summaryText(cmp.score), 'margin-top:16px');

    // По блокам
    html += h2('Согласованность по блокам');
    var rows = '';
    BLOCKS.forEach(function (bl) {
      var b = cmp.blocks[bl.id];
      if (!b) return;
      var col = b.score >= 70 ? C.good : b.score >= 45 ? C.warn : C.bad;
      rows += '<div style="margin:0 0 14px"><table role="presentation" width="100%" cellpadding="0" cellspacing="0"><tr>' +
        '<td style="font:500 14px/1.4 ' + FONT + ';color:' + C.ink + '">' + esc(bl.title) + (bl.weight >= 3 ? ' <span style="color:' + C.muted + ';font-weight:400">· важный блок</span>' : '') + '</td>' +
        '<td style="font:600 14px/1.4 ' + FONT + ';color:' + col + ';text-align:right;white-space:nowrap">' + b.score + '%</td></tr></table>' +
        bar(b.score, col) +
        '<div style="font:400 12px/1.4 ' + FONT + ';color:' + C.muted + ';margin-top:4px">совпало ' + b.counts.match + ' · близко ' + b.counts.close + ' · по-разному ' + b.counts.differ + ' · противоположно ' + b.counts.opposite + '</div></div>';
    });
    html += card(rows + muted('Расхождения в быте и отдыхе переживаются легче всего, расхождения в конфликтах и ценностях требуют разговора — поэтому эти блоки весят больше.'));

    // Оси
    html += h2('Ваши оси');
    var axHtml = '';
    AXIS_ORDER.forEach(function (k) {
      if (AXES[k].sex && !sexBoth) return;
      var va = axisScore(A, k), vb = axisScore(B, k);
      if (va == null || vb == null) return;
      axHtml += axisRow(AXES[k].title, AXES[k].lo, AXES[k].hi, va, vb, A.name, B.name);
    });
    html += card(axHtml);

    // Динамики
    var hard = dyn.filter(function (d) { return d.level !== 'good'; });
    var good = dyn.filter(function (d) { return d.level === 'good'; });
    if (hard.length) { html += h2('Главное, на что стоит обратить внимание'); hard.forEach(function (d) { html += dynCard(d); }); }

    html += '<!--CLAUDE-->';

    // Опоры
    var supports = cmp.items.filter(function (it) { return it.rel === 'match' && BBY[it.q.block].weight >= 2; });
    if (good.length || supports.length) {
      html += h2('Ваши опоры');
      good.forEach(function (d) { html += dynCard(d); });
      if (supports.length) {
        html += card('<div style="font:600 15px/1.4 ' + FONT + ';color:' + C.ink + ';margin:0 0 8px">Вы ответили одинаково</div>' +
          supports.map(function (it) {
            return '<div style="margin:0 0 8px;font:400 14px/1.45 ' + FONT + ';color:' + C.ink + '"><span style="color:' + C.muted + '">' + esc(it.q.text) + '</span> ' + esc(optText(it.q.id, it.x)) + '</div>';
          }).join('') + muted('Совпадения тоже стоит отметить вслух — это то, на что можно опираться в трудные моменты.'));
      }
    }

    // Зоны договорённостей
    var zones = cmp.items.filter(function (it) { return (it.rel === 'opposite' || it.rel === 'differ') && it.q.tip; });
    zones.sort(function (x, y) {
      var rx = x.rel === 'opposite' ? 0 : 1, ry = y.rel === 'opposite' ? 0 : 1;
      return rx - ry || BBY[y.q.block].weight - BBY[x.q.block].weight || x.q.id - y.q.id;
    });
    if (zones.length) {
      html += h2('Где ваши ответы разошлись');
      html += zones.map(function (it) {
        var tag = it.rel === 'opposite' ? '<span style="color:' + C.bad + '">противоположно</span>' : '<span style="color:' + C.warn + '">по-разному</span>';
        return card(
          '<div style="font:400 12px/1.4 ' + FONT + ';color:' + C.muted + ';margin:0 0 4px">' + esc(BBY[it.q.block].title) + ' · ' + tag + '</div>' +
          '<div style="font:600 15px/1.4 ' + FONT + ';color:' + C.ink + ';margin:0 0 8px">' + esc(it.q.text) + '</div>' +
          '<div style="font:400 14px/1.5 ' + FONT + ';margin:0 0 2px"><b style="color:' + C.a + '">' + esc(A.name) + ':</b> ' + esc(optText(it.q.id, it.x)) + '</div>' +
          '<div style="font:400 14px/1.5 ' + FONT + ';margin:0 0 8px"><b style="color:' + C.b + '">' + esc(B.name) + ':</b> ' + esc(optText(it.q.id, it.y)) + '</div>' +
          '<div style="font:400 14px/1.5 ' + FONT + ';color:' + C.muted + '">' + esc(it.q.tip) + '</div>');
      }).join('');
    }

    // Портреты
    html += h2('Психологический портрет: <span style="color:' + C.a + '">' + esc(A.name) + '</span>');
    html += portraitHtml(A);
    html += h2('Психологический портрет: <span style="color:' + C.b + '">' + esc(B.name) + '</span>');
    html += portraitHtml(B);

    // Рекомендации
    var recs = [], seen = {};
    hard.forEach(function (d) { var k = plain(d.rec); if (d.rec && !seen[k]) { seen[k] = 1; recs.push(d.rec); } });
    recs = recs.slice(0, 6);
    GENERAL_RECS.forEach(function (r) { if (recs.length < 8) recs.push(esc(r)); });
    html += h2('Рекомендации для развития отношений');
    html += card('<ol style="margin:0;padding:0 0 0 20px">' + recs.map(function (r) {
      return '<li style="font:400 15px/1.55 ' + FONT + ';color:' + C.ink + ';margin:0 0 10px">' + r + '</li>';
    }).join('') + '</ol>');

    html += muted('Разные ответы — не «несовместимость», а карта того, где придётся договариваться. Этот разбор построен по вашим ответам и не заменяет консультацию психолога. Если какая-то тема вызывает у вас сильную боль или ссоры повторяются по кругу, обратиться к семейному терапевту — признак зрелости пары, а не слабости.');

    return { score: cmp.score, html: html, dynamics: dyn, blocks: cmp.blocks, text: reportText(A, B, cmp, dyn) };
  }

  // Текстовая сводка для Claude (и для логов)
  function reportText(A, B, cmp, dyn) {
    var lines = ['Партнёр A: ' + A.name, 'Партнёр B: ' + B.name, 'Индекс согласованности: ' + cmp.score + '%', '', 'Ответы:'];
    QS.forEach(function (q) {
      var x = keys(A, q.id), y = keys(B, q.id);
      if (!x.length && !y.length) return;
      lines.push(q.id + '. [' + BBY[q.block].title + '] ' + q.text + '\n   A: ' + optText(q.id, x) + '\n   B: ' + optText(q.id, y));
    });
    lines.push('', 'Найденные динамики:');
    dyn.forEach(function (d) { lines.push('- (' + d.level + ') ' + d.title + ': ' + plain(d.text)); });
    return lines.join('\n');
  }

